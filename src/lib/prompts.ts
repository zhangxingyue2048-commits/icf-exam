/** 生成学习报告 AI 建议 prompt */
export function buildReportPrompt(
  level: ExamLevel,
  weakTopics: string[],
  topicStats: Record<string, { total: number; correct: number }>
): string {
  const statsText = Object.entries(topicStats)
    .map(([topic, s]) => `${topic}：${s.correct}/${s.total}题正确`)
    .join('、')

  const weakText = weakTopics.length > 0
    ? `薄弱专项：${weakTopics.join('、')}`
    : '暂无明显薄弱专项'

  return `你是ICF${level}备考导师。学员最近10题答题情况如下：
${statsText}
${weakText}

请用温暖鼓励的语气，给出200字以内的个性化学习建议：
1. 肯定学员的进步
2. 针对薄弱专项给出具体改进方向
3. 推荐下一步练习重点
语气专业温暖，不说"你答错了"，用"我们来看看"视角。`
}
