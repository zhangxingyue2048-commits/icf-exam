/** 从题库中按 competency 筛选，再随机抽一道 */
export function pickReferenceQuestion(
  mode: 'random' | 'knowledge' | 'sjt',
  competency?: string
) {
  if (mode === 'knowledge') return null // 知识类不使用题库参考

  let pool = [...QUESTION_BANK]

  if (competency) {
    const filtered = pool.filter((q) =>
      q.competency.split(',').map((s) => s.trim()).includes(competency)
    )
    if (filtered.length > 0) pool = filtered
  }

  return pool[Math.floor(Math.random() * pool.length)]
}

