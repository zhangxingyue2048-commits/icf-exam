type ExamLevel = 'ACC' | 'PCC' | 'MCC'

/** 根据级别和题目序号决定出题类型 */
export function selectQuestionType(level: ExamLevel, questionIndex: number): 'knowledge' | 'sjt' {
  if (level === 'ACC') return 'knowledge'
  if (level === 'MCC') return questionIndex % 3 === 0 ? 'knowledge' : 'sjt'
  // PCC: 交替出题
  return questionIndex % 2 === 0 ? 'knowledge' : 'sjt'
}

